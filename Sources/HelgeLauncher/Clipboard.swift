import AppKit

/// Polls NSPasteboard.changeCount and keeps a persisted history of text, links, files and images.
final class ClipboardHistory {
    static let shared = ClipboardHistory()

    struct Entry: Codable {
        var id: String
        var kind: String        // text | link | file | image | color
        var text: String        // text, URL, file path or image file name
        var app: String?
        var date: Double
        var pinned: Bool = false
    }

    private(set) var entries: [Entry] = []
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private let url = Paths.supportDir.appendingPathComponent("clipboard.json")
    private let imageDir = Paths.supportDir.appendingPathComponent("clipboard-images")
    var config = ClipboardConfig()

    init() {
        try? FileManager.default.createDirectory(at: imageDir, withIntermediateDirectories: true)
        if let d = try? Data(contentsOf: url), let e = try? JSONDecoder().decode([Entry].self, from: d) { entries = e }
    }

    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
    }

    func stop() { timer?.invalidate(); timer = nil }

    func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = pb.types ?? []
        // Respect nspasteboard.org markers set by password managers.
        if types.contains(where: { ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"].contains($0.rawValue) }) { return }
        let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let app, config.ignoreApps.contains(app) { return }

        var entry: Entry?
        if let files = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], let f = files.first {
            entry = Entry(id: UUID().uuidString, kind: "file", text: f.path, app: app, date: now)
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let kind = (s.hasPrefix("http://") || s.hasPrefix("https://")) && !s.contains(" ") ? "link"
                : s.range(of: "^#[0-9a-fA-F]{6}$", options: .regularExpression) != nil ? "color" : "text"
            entry = Entry(id: UUID().uuidString, kind: kind, text: s, app: app, date: now)
        } else if let img = NSImage(pasteboard: pb), let tiff = img.tiffRepresentation,
                  let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) {
            let name = UUID().uuidString + ".png"
            try? png.write(to: imageDir.appendingPathComponent(name))
            entry = Entry(id: UUID().uuidString, kind: "image", text: name, app: app, date: now)
        }
        guard var e = entry else { return }
        // Re-copying moves the existing entry to the top.
        if let i = entries.firstIndex(where: { $0.kind == e.kind && $0.text == e.text }) {
            e.pinned = entries[i].pinned
            entries.remove(at: i)
        }
        entries.insert(e, at: 0)
        trim()
        save()
    }

    private var now: Double { Date().timeIntervalSince1970 }

    private func trim() {
        var unpinned = 0
        entries = entries.filter { e in
            if e.pinned { return true }
            unpinned += 1
            if unpinned > config.maxItems {
                if e.kind == "image" { try? FileManager.default.removeItem(at: imageDir.appendingPathComponent(e.text)) }
                return false
            }
            return true
        }
    }

    private func save() {
        if let d = try? JSONEncoder().encode(entries) { try? d.write(to: url, options: .atomic) }
    }

    func togglePin(_ id: String) {
        guard let i = entries.firstIndex(where: { $0.id == id }) else { return }
        entries[i].pinned.toggle()
        save()
    }

    func delete(_ id: String) {
        entries.removeAll { $0.id == id }
        save()
    }

    /// Puts an entry back on the pasteboard (without re-recording it as new).
    func restore(_ e: Entry) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch e.kind {
        case "file": pb.writeObjects([URL(fileURLWithPath: e.text) as NSURL])
        case "image": if let img = NSImage(contentsOf: imageDir.appendingPathComponent(e.text)) { pb.writeObjects([img]) }
        default: pb.setString(e.text, forType: .string)
        }
        lastChange = pb.changeCount
        if let i = entries.firstIndex(where: { $0.id == e.id }) {
            var moved = entries.remove(at: i)
            moved.date = now
            entries.insert(moved, at: 0)
            save()
        }
    }

    var items: [Item] {
        let ordered = entries.filter(\.pinned) + entries.filter { !$0.pinned }
        let rel = RelativeDateTimeFormatter()
        rel.unitsStyle = .short
        return ordered.map { e in
            let title: String
            let icon: ItemIcon
            switch e.kind {
            case "image": title = "Image"; icon = .file(imageDir.appendingPathComponent(e.text).path)
            case "file": title = (e.text as NSString).lastPathComponent; icon = .file(e.text)
            case "link": title = e.text; icon = .symbol("link")
            case "color": title = e.text; icon = .symbol("paintpalette")
            default:
                title = e.text.trimmingCharacters(in: .whitespacesAndNewlines).components(separatedBy: .newlines).first ?? ""
                icon = .symbol("doc.plaintext")
            }
            return Item(
                id: "clip:" + e.id, title: String(title.prefix(200)),
                subtitle: rel.localizedString(for: Date(timeIntervalSince1970: e.date), relativeTo: Date()),
                icon: icon, keywords: e.kind == "text" ? [e.text] : [],
                accessory: e.pinned ? "Pinned" : "",
                actions: [
                    Action(title: "Paste") {
                        self.restore(e)
                        Launcher.shared?.hide()
                        DispatchQueue.main.asyncAfter(deadline: .now() + 0.08) { Pasteboard.sendCmdV() }
                        return false
                    },
                    Action(title: "Copy") { self.restore(e); return false },
                    Action(title: e.pinned ? "Unpin" : "Pin") { self.togglePin(e.id); return true },
                    Action(title: "Delete") { self.delete(e.id); return true },
                ],
                preview: e.kind == "image" ? nil : e.text)
        }
    }
}
